#!/usr/bin/env clojure
(ns parity
  "Objective parity report: compares this implementation against the original
  Go repository, so progress is measured rather than claimed.

  Usage: clojure -M scripts/parity.clj /path/to/shelley-ref

  Writes PARITY-GAPS.md: routes, tools and migrations, present or missing."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]))

(defn- read-root [root]
  (filter #(str/ends-with? (.getName %) ".clj") (file-seq (io/file root))))

(defn- clj-files [root] (read-root (str root "/src")))

;; ---------------------------------------------------------------------------
;; Routes

(def route-re  (re-pattern "mux\\.Handle(?:Func)?\\(\"(GET|POST|PUT|DELETE|PATCH) ([^\"]+)\""))
(def ours-re   (re-pattern "\\[\"([^\"]+)\" \\{([^}]*)\\}"))
(def verbs-re  (re-pattern ":(get|post|put|delete|patch)\\b"))

(defn orig-routes [ref]
  (->> (.listFiles (io/file ref "server"))
       (filter #(and (str/ends-with? (.getName %) ".go")
                     (not (str/ends-with? (.getName %) "_test.go"))))
       (mapcat (fn [f] (map rest (re-seq route-re (slurp f)))))
       (map (fn [[verb path]] (str verb " " (str/replace path #"\{[^}]+\}" ":id"))))
       set))

(defn our-routes [root]
  (->> (clj-files root)
       (mapcat (fn [f]
                 (for [[_ pattern methods] (re-seq ours-re (slurp f))
                       [_ verb] (re-seq verbs-re methods)]
                   (str (str/upper-case verb) " "
                        (str/replace pattern #"\{[^}]+}" ":id")))))
       set))

;; ---------------------------------------------------------------------------
;; Tools and migrations

(defn orig-tools [ref]
  (->> (re-seq #"\{Name: \"([^\"]+)\"" (slurp (io/file ref "claudetool/registry.go")))
       (map second) set))

(defn our-tools [root]
  (->> (cons (io/file root "src/shelley/tools.clj") (read-root (str root "/src/shelley/tools")))
       (mapcat (fn [f] (map second (re-seq #"\{:name \"([^\"]+)\"" (slurp f)))))
       set))

(defn orig-migrations [ref]
  (->> (.listFiles (io/file ref "db/schema"))
       (map #(.getName %)) set))

(defn our-migrations [root]
  (->> (read-root (str root "/src/shelley/db"))
       (mapcat (fn [f] (map second (re-seq #"\"([0-9]{3}-[a-z0-9-]+)\"" (slurp f)))))
       set))

;; ---------------------------------------------------------------------------

(defn -main [& [ref]]
  (let [ref (or ref "/tmp/shelley-ref")
        root "."
        ours-r (our-routes root) theirs-r (orig-routes ref)
        ours-t (our-tools root)  theirs-t (orig-tools ref)
        ours-m (our-migrations root) theirs-m (orig-migrations ref)
        route-gap (sort (remove ours-r theirs-r))
        tool-gap (sort (remove ours-t theirs-t))
        mig-gap (sort (remove ours-m theirs-m))
        section (fn [title mine theirs gaps]
                  (str "## " title "\n\n"
                       (format "original %d · implemented %d · missing %d\n\n"
                               (count theirs) (count (filter mine theirs)) (count gaps))
                       (if (seq gaps)
                         (str "```\n" (str/join "\n" gaps) "\n```\n\n")
                         "all present\n\n")))]
    (spit "PARITY-GAPS.md"
          (str "# Parity gaps (generated)\n\n"
               "Generated by `clojure -M scripts/parity.clj " ref "`.\n"
               "Paths are normalised (`{id}` → `:id`); a renamed route counts as missing, so treat\n"
               "this as a worklist rather than a verdict.\n\n"
               (section "HTTP routes" ours-r theirs-r route-gap)
               (section "Tools" ours-t theirs-t tool-gap)
               (section "Migrations" ours-m theirs-m mig-gap)))
    (println (format "routes %d/%d  tools %d/%d  migrations %d/%d"
                     (count (filter ours-r theirs-r)) (count theirs-r)
                     (count (filter ours-t theirs-t)) (count theirs-t)
                     (count (filter ours-m theirs-m)) (count theirs-m)))
    (println "wrote PARITY-GAPS.md")))

(apply -main *command-line-args*)
